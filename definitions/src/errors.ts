export type FormulaErrorCode = (typeof FormulaErrorCodes)[keyof typeof FormulaErrorCodes];

export interface FormulaError {
  kind: FormulaErrorKind;
  code: FormulaErrorCode;
  message: string;
  span?: SourceSpan;
  path?: string[];
}

export function makeFormulaError(input: FormulaError): FormulaError {
  return input;
}
