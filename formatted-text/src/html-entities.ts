const HTML5_REFERENCES: ReadonlyArray<readonly [string, number]> = [['apos', 39]];

/** Every HTML 4 named character reference and `&apos;`, by its case-sensitive name. */
export const HTML_NAMED_CHARACTER_REFERENCES: ReadonlyMap<string, string> = new Map<string, string>(
  [
    ...LATIN_1_NAMES.map(
      (name, index) => [name, String.fromCharCode(LATIN_1_FIRST_CODE_POINT + index)] as const,
    ),
    ...[...SYMBOL_REFERENCES, ...SPECIAL_REFERENCES, ...HTML5_REFERENCES].map(
      ([name, codePoint]) => [name, String.fromCodePoint(codePoint)] as const,
    ),
  ],
);

